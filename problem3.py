def print_range(start,stop,step):
  """
  signature: number, number, number --> range of numbers 
  explanation: this function takes in 3 values start stop and step. while start is less than stop the function prints all numbers plus step
  >>> print_range(1,10,2)
  1
  3
  5
  7
  9
  >>> print_range(1,20,5)
  1
  6
  11
  16
  >>> print_range(1,10,3)
  1
  4
  7
  >>> print_range(10,50,5)
  10
  15
  20
  25
  30
  35
  40
  45
  """
  while start < stop:
    print(start)
    start+=step












 

